#61. while - Condição em detalhes

'''
Repetições
while (enquanto)
Executa uma ação enquanto uma condição for verdadeira

Loop infinito --> Quando um código não tem fim

um circulo até alguma coisa acontecer
'''
contador = 0

while contador < 20:
    contador = contador + 1
    print(contador)

print('Acabou')    