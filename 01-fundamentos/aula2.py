# print = função usada para mostrar algo na tela, dentro tem o  "argumentos" e os "argumentos nomeados"

# sep = define o separador entre os valores (aqui está vazio '')
# end = define o final da linha (aqui coloca '#', então não pula linha)
print(12, 34, 1011, sep='', end='#')

# sep = coloca '-' entre os números
# end = '\n' significa pular linha (é o padrão do print)
print(56, 78, sep='-', end='\n')

# mesma coisa aqui
print(9, 10, sep='-', end='\n')
